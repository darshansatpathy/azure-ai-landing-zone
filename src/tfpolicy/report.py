"""Render a Report as text, JSON, Markdown or SARIF 2.1.0."""

from __future__ import annotations

import json
from collections import Counter

from . import __version__
from .engine import SEVERITIES, Finding, Report, RuleInfo, all_rules

_LEVEL = {"critical": "error", "high": "error", "medium": "warning", "low": "note", "info": "note"}


def to_text(report: Report, fail_on: str) -> str:
    lines: list[str] = []
    for f in report.active:
        lines.append(
            f"{f.file}:{f.line}: {f.severity.upper()} {f.rule_id} {f.message} [{f.resource}]"
        )
    for f in report.suppressed:
        lines.append(f"{f.file}:{f.line}: suppressed {f.rule_id} ({f.reason})")
    failing = report.failing(fail_on)
    lines.append(
        f"{len(report.modules)} modules, {len(report.rules_run)} rules: "
        f"{len(report.active)} findings ({len(failing)} at or above {fail_on}), "
        f"{len(report.suppressed)} suppressed"
    )
    return "\n".join(lines) + "\n"


def to_json(report: Report, fail_on: str) -> str:
    return (
        json.dumps(
            {
                "tool": "tfpolicy",
                "version": __version__,
                "modules": report.modules,
                "rules": report.rules_run,
                "disabled": report.disabled,
                "fail_on": fail_on,
                "findings": [f.to_dict() for f in report.findings],
            },
            indent=2,
        )
        + "\n"
    )


def to_markdown(report: Report, fail_on: str) -> str:
    counts = Counter(f.severity for f in report.active)
    out = ["# Policy check", ""]
    out.append(
        f"{len(report.modules)} modules checked against {len(report.rules_run)} rules. "
        f"{len(report.active)} findings, {len(report.suppressed)} suppressed with a written reason."
    )
    out.append("")
    out.append("| Severity | Findings |")
    out.append("|---|---|")
    for sev in reversed(SEVERITIES):
        out.append(f"| {sev} | {counts.get(sev, 0)} |")
    if report.active:
        out += [
            "",
            "## Findings",
            "",
            "| Rule | Severity | Location | Message |",
            "|---|---|---|---|",
        ]
        for f in report.active:
            out.append(f"| {f.rule_id} | {f.severity} | `{f.file}:{f.line}` | {f.message} |")
    if report.suppressed:
        out += ["", "## Suppressions", "", "| Rule | Location | Reason |", "|---|---|---|"]
        for f in report.suppressed:
            out.append(f"| {f.rule_id} | `{f.file}:{f.line}` | {f.reason} |")
    if report.disabled:
        out += ["", "## Disabled rules", "", "| Rule | Reason |", "|---|---|"]
        for k, v in sorted(report.disabled.items()):
            out.append(f"| {k} | {v} |")
    return "\n".join(out) + "\n"


def _sarif_rule(r: RuleInfo) -> dict[str, object]:
    return {
        "id": r.id,
        "name": r.title,
        "shortDescription": {"text": r.title},
        "fullDescription": {"text": r.rationale},
        "help": {"text": f"{r.remediation} ({r.benchmark})"},
        "defaultConfiguration": {"level": _LEVEL[r.severity]},
        "properties": {"tags": ["security", "terraform"], "security-severity": _score(r.severity)},
    }


def _score(sev: str) -> str:
    return {"critical": "9.5", "high": "8.0", "medium": "5.5", "low": "3.0", "info": "1.0"}[sev]


def _sarif_result(f: Finding) -> dict[str, object]:
    res: dict[str, object] = {
        "ruleId": f.rule_id,
        "level": _LEVEL.get(f.severity, "note"),
        "message": {"text": f.message},
        "locations": [
            {
                "physicalLocation": {
                    "artifactLocation": {"uri": f.file},
                    "region": {"startLine": max(1, f.line)},
                }
            }
        ],
    }
    if f.suppressed:
        res["suppressions"] = [{"kind": "inSource", "justification": f.reason}]
    return res


def to_sarif(report: Report, fail_on: str) -> str:
    doc = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [
            {
                "tool": {
                    "driver": {
                        "name": "tfpolicy",
                        "version": __version__,
                        "informationUri": "https://github.com/darshansatpathy/azure-ai-landing-zone",
                        "rules": [_sarif_rule(r) for r in all_rules()],
                    }
                },
                "results": [_sarif_result(f) for f in report.findings if f.rule_id != "TFP-PARSE"]
                + [_sarif_result(f) for f in report.findings if f.rule_id == "TFP-PARSE"],
            }
        ],
    }
    return json.dumps(doc, indent=2) + "\n"


def rules_markdown() -> str:
    out = [
        "# Policy rules",
        "",
        "Generated by `tfpolicy rules --format markdown`. Do not edit by hand.",
        "",
        "| ID | Severity | Rule | Reference |",
        "|---|---|---|---|",
    ]
    rules = all_rules()
    for r in rules:
        out.append(f"| {r.id} | {r.severity} | {r.title} | {r.benchmark} |")
    out.append("")
    for r in rules:
        out += [
            f"## {r.id}: {r.title}",
            "",
            f"**Severity:** {r.severity}  ",
            f"**Reference:** {r.benchmark}",
            "",
            f"**Why it matters.** {r.rationale}",
            "",
            f"**How to fix it.** {r.remediation}",
            "",
        ]
    return "\n".join(out)
